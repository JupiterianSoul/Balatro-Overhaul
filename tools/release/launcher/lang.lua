function L.detect(getenv)
    local s = (getenv("OVERHAUL_LANG") or getenv("LANGUAGE") or getenv("LC_ALL") or getenv("LC_MESSAGES") or getenv("LANG") or ""):lower()
    local code = s:match("^(%a%a)")
    if code and L[code] and L.names[code] then
        return code
    end
    return "en"
end

